// LONG_MAX_WORDS used to be a second copy of this number, kept in step by hand.
const mins = (words: number) => Math.round((words / 145) * 10) / 10;

/**
 * How long a render actually takes, and why.
 *
 * These are measured from production, not estimated: a 3:33 Direct Video took
 * ~9 minutes end to end, and a ~4:00 Video Agent render took ~18. The screens
 * used to promise "5 to 8 min" for the Video Agent path specifically, which is
 * the slowest one — so a perfectly normal render looked like a hang.
 *
 * The branch mirrors the server's own choice in create-blog: a pasted script
 * and every long video render through Direct Video (a straight read), while an
 * AI-written short goes to HeyGen's Video Agent, which additionally plans the
 * scenes and picks the visuals. That extra work is the whole difference.
 */
function renderEta(opts: { pastedScript: boolean; longForm: boolean }): {
  range: string;
  why: string;
} {
  const usesVideoAgent = !opts.pastedScript && !opts.longForm;
  if (usesVideoAgent) {
    return {
      range: "15–20 minutes",
      why: "The AI plans the scenes and chooses the visuals, which takes longer than a straight read.",
    };
  }
  return opts.longForm
    ? { range: "10–20 minutes", why: "Long videos read your full script start to finish." }
    : { range: "5–10 minutes", why: "" };
}

/**
 * Scripts are clamped at render time, which used to happen silently — a pasted
 * 1,200-word script became a 580-word video with no explanation. This says so
 * up front and offers the one-click fix.
 */
function ScriptLengthWarning({
  words,
  isLong,
  standardCap,
  onSwitchToLong,
}: {
  words: number;
  isLong: boolean;
  standardCap: number;
  onSwitchToLong?: () => void;
}) {
  const cap = isLong ? LONG_MAX_WORDS : standardCap;
  if (words <= cap) return null;
  // The fill is the share of the script that survives the clamp and the tick
  // sits on the cap, so the empty run after it is literally what gets cut.
  const kept = Math.max(0, Math.min(100, (cap / words) * 100));
  return (
    <div className="mt-2 flex items-center gap-2.5 rounded-lg border border-[#e3c48f] bg-spark-amber-tint px-3 py-2.5">
      <div className="min-w-0 flex-1">
        <div className="relative h-[5px] rounded-full bg-spark-rule-soft">
          <div
            className="h-full rounded-full bg-spark-amber"
            style={{ width: `${kept}%` }}
          />
          <div
            className="absolute top-[-3px] h-[11px] w-[1.5px] rounded-full bg-spark-ink"
            style={{ left: `${kept}%` }}
            aria-hidden="true"
          />
        </div>
        <p className="mt-1.5 text-[11px] leading-snug text-spark-ink-soft">
          {words} of {cap} words for a {isLong ? "long" : "standard"} {mins(cap)}-minute
          video — the tail will be trimmed.
        </p>
      </div>
      {!isLong && onSwitchToLong && (
        <button
          type="button"
          onClick={onSwitchToLong}
          className="flex-none whitespace-nowrap rounded-nav bg-spark-ink px-3 py-1.5 text-[11px] font-medium text-white transition-opacity hover:opacity-85"
        >
          Switch to 8 min
        </button>
      )}
    </div>
  );
}

